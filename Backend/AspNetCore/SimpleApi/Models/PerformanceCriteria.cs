using System.ComponentModel.DataAnnotations;

namespace SimpleApi.Models
{
    /// <summary>
    /// Performance criteria for evaluating users based on their role.
    /// Criteria can be manually created or AI-generated.
    /// </summary>
    public class PerformanceCriteria
    {
        public int Id { get; set; }

        /// <summary>
        /// The user role this criteria applies to (e.g., User, Manager, Writer, etc.)
        /// </summary>
        [Required]
        public UserRole UserRole { get; set; }

        [Required]
        [MaxLength(200)]
        public string Name { get; set; } = string.Empty;

        [MaxLength(1000)]
        public string? Description { get; set; }

        [MaxLength(100)]
        public string? Category { get; set; }

        /// <summary>
        /// Weight percentage for this criteria in overall evaluation (0-100)
        /// </summary>
        [Range(0, 100)]
        public decimal WeightPercentage { get; set; }

        [MaxLength(200)]
        public string? MeasurementMethod { get; set; }

        [MaxLength(200)]
        public string? ScoringMethod { get; set; }

        public decimal? TargetValue { get; set; }

        public decimal? MinimumThreshold { get; set; }

        public decimal? MaximumThreshold { get; set; }

        public bool IsActive { get; set; } = true;

        /// <summary>
        /// Flag to indicate if this criteria was generated by AI (for future AI integration)
        /// </summary>
        public bool CreatedByAI { get; set; } = false;

        public DateTime CreatedDate { get; set; } = DateTime.UtcNow;

        public DateTime ModifiedDate { get; set; } = DateTime.UtcNow;

        // Foreign key for Company (Multi-tenant support)
        public int CompanyId { get; set; }

        // Navigation property
        public virtual Company? Company { get; set; }
    }
}
